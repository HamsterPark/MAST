/**
 * Station capabilities: what this station has, as the UI gates on it. Pure functions only
 * (no React, no fetch), so `node --test` runs them (test/stationCapabilities.test.ts).
 *
 * ── Why capabilities and not the profile name ──
 * There are three profiles now (stm / optical / generic, lib/stationProfile.ts), and more
 * kinds of station will come. Asking "is this the optical station?" in eight files meant
 * every new kind of station had to visit all eight. Instead the service reports what the
 * station has (`GET /api/health` `station_capabilities`, a list of names), and every gate
 * in the UI asks for one capability: the Nanonis polls ask for `nanonis`, the scan map
 * asks for `scan_map`, the operator prompts ask for `operator_prompts`.
 *
 * ── A service that does not send the list ──
 * A backend from before the list existed sends only `station_profile`. Then the list is
 * derived from the profile with DEFAULT_CAPABILITIES, the same table the backend uses
 * (contract: docs/v2/design/generic_station.md), so a new UI on an old service behaves
 * exactly as the old UI did. Nothing answered yet, or an unreadable answer, is the default
 * profile "stm" and therefore the STM capabilities: the machine every installation was
 * before profiles existed keeps everything it had.
 *
 * The field is read through a local type guard (`readCapabilityList`) rather than the
 * generated `schema.d.ts` type, so this works before and after the schema is regenerated.
 *
 * Capability names are identity strings (sent over the API, compared). They are never
 * wrapped in `tr()`; only the labels below are.
 */

import { tr } from "./i18n.ts";
import stationTable from "./stationCapabilities.json" with { type: "json" };
import { normalizeProfile, type StationProfile } from "./stationProfile.ts";

/**
 * The names this build gates on, as a literal union so a typo in a gate is a compile error.
 * `CAPABILITIES` below comes from the generated table, and test/stationCapabilities.test.ts
 * pins the two to each other.
 */
export type Capability =
  | "nanonis"
  | "stm_safety"
  | "stm_actions"
  | "scan_map"
  | "witec"
  | "optical_bench"
  | "operator_prompts"
  | "laser_safety"
  | "sensor_echo";

/**
 * The backend's own table, generated by `MASTv2/scripts/dump_station_capabilities.py` from
 * `mast/station.py` and copied here unchanged (never edit that file by hand). Everything
 * below is read from it, so the UI and the backend cannot drift apart.
 */
const TABLE = stationTable as {
  capabilities: Capability[];
  profiles: Record<StationProfile, Capability[]>;
  requires: Partial<Record<Capability, Capability[]>>;
};

/** Every capability this build gates on, in the contract's order (generic_station.md section 1.2). The service may report others; they are kept. */
export const CAPABILITIES: readonly Capability[] = Object.freeze([...TABLE.capabilities]);

/**
 * What a profile has when the service does not say (generic_station.md section 1.2,
 * `PROFILE_CAPABILITIES`), in table order.
 */
export const DEFAULT_CAPABILITIES: Readonly<Record<StationProfile, readonly Capability[]>> = Object.freeze({
  stm: Object.freeze([...TABLE.profiles.stm]),
  optical: Object.freeze([...TABLE.profiles.optical]),
  generic: Object.freeze([...TABLE.profiles.generic]),
});

/**
 * What a capability needs (`CAPABILITY_REQUIRES`): every profile's set is closed under it.
 * The STM pieces need the Nanonis link; laser safety lives in the operator service.
 */
export const CAPABILITY_REQUIRES: Readonly<Partial<Record<Capability, readonly Capability[]>>> = Object.freeze(
  Object.fromEntries(Object.entries(TABLE.requires).map(([k, v]) => [k, Object.freeze([...(v ?? [])])])),
);

/**
 * Serial auto-detection on this station (`GET /api/health` `station_serial_autodetect`,
 * generic_station.md §1.4): "default_on" (STM: as configured), "default_off" (generic: off
 * unless the operator switches it on), "forced_off" (optical). Not a capability.
 */
export type SerialAutodetect = "default_on" | "default_off" | "forced_off";

/** The field, or null when the service does not send it (an older backend) or sends junk. */
export function readSerialAutodetect(health: unknown): SerialAutodetect | null {
  const v = (typeof health === "object" && health !== null ? health : {}) as { station_serial_autodetect?: unknown };
  const s = v.station_serial_autodetect;
  return s === "default_on" || s === "default_off" || s === "forced_off" ? s : null;
}

/** "server": the service sent the list. "derived": it did not, the list comes from the profile. */
export type CapabilitySource = "server" | "derived";

export interface StationCapabilities {
  /** The profile in force (`station_profile`), "stm" when unknown. */
  profile: StationProfile;
  /** Every capability name, in the order reported, including names this build does not know. */
  names: readonly string[];
  source: CapabilitySource;
  has(cap: Capability): boolean;
}

/**
 * `station_capabilities` as a clean list, or null when the field is not a list of names.
 *
 * Absent, null, a string, an object, or a list with anything but strings in it: null, and
 * the caller derives the list from the profile. A malformed list is not trusted as "this
 * station has nothing": on an STM station that would hide the Nanonis readouts over a bug.
 * An empty list is a real answer (a station with none of these capabilities).
 * Names are trimmed and lower-cased; duplicates and empty names are dropped.
 */
export function readCapabilityList(v: unknown): string[] | null {
  if (!Array.isArray(v)) return null;
  if (!v.every((x) => typeof x === "string")) return null;
  const out: string[] = [];
  for (const raw of v as string[]) {
    const name = raw.trim().toLowerCase();
    if (name && !out.includes(name)) out.push(name);
  }
  return out;
}

/** The capabilities of a `GET /api/health` answer (`undefined` = not answered yet). */
export function capabilitiesFrom(health: unknown): StationCapabilities {
  const h = (typeof health === "object" && health !== null ? health : {}) as {
    station_profile?: unknown;
    station_capabilities?: unknown;
  };
  const profile = normalizeProfile(h.station_profile);
  const reported = readCapabilityList(h.station_capabilities);
  const names: readonly string[] = Object.freeze(reported ?? [...DEFAULT_CAPABILITIES[profile]]);
  const set = new Set(names);
  return {
    profile,
    names,
    source: reported ? "server" : "derived",
    has: (cap: Capability) => set.has(cap),
  };
}

/** Operator-facing name of a capability, for the notice on a page this station does not have. */
export function capabilityLabel(cap: Capability): string {
  switch (cap) {
    case "nanonis":
      return tr("Nanonis 控制器", "a Nanonis controller");
    case "stm_safety":
      return tr("STM 安全参数（前放、安全包络、进退针）", "the STM safety parameters (preamp, safety envelope, approach and retract)");
    case "stm_actions":
      return tr("STM 动作（扫描、谱学、退针）", "the STM actions (scanning, spectroscopy, withdrawing the tip)");
    case "scan_map":
      return tr("STM 扫描帧", "STM scan frames");
    case "witec":
      return tr("WITec 拉曼系统", "a WITec Raman system");
    case "optical_bench":
      return tr("光学台 / 外部设备", "the optical bench / configured devices");
    case "operator_prompts":
      return tr("操作员提示服务", "the operator prompt service");
    case "laser_safety":
      return tr("激光安全（签署与撤销关光）", "laser safety (attestation, light off on withdrawal)");
    case "sensor_echo":
      return tr("环境读数回显", "the environment readings echo");
  }
}

/**
 * Which overview the home page shows. A station with Nanonis gets the STM overview; one with
 * WITec but no Nanonis the optical one; anything else the generic one. Which sections the
 * overview then carries is decided per capability (devices: `optical_bench`; environment
 * sensors: `sensor_echo`), see DashboardPage.
 */
export type OverviewKind = "stm" | "optical" | "generic";

export function overviewKind(has: (cap: Capability) => boolean): OverviewKind {
  if (has("nanonis")) return "stm";
  if (has("witec")) return "optical";
  return "generic";
}

/**
 * The E-STOP button's tooltip: what pressing it does on this station, as the backend does it
 * (`core/runtime.py` `emergency_stop`, generic_station.md §3.7).
 *
 * - With Nanonis (an STM station): today's text, word for word. It is pinned as a snapshot;
 *   the STM station's top bar does not change.
 * - Without: every station runs the optics / satellite side (satellite E-STOP, the local
 *   optical stage's `stop_all`, `safe_off_all`: every laser off, every microscope shutter
 *   closed, read back), the magnet STOP and the heater RANGE 0; what it does not do is the
 *   Nanonis part (stop the motors, withdraw the tip). The text says exactly that, so it does
 *   not depend on `laser_safety` (light-off on revocation is another matter).
 */
export function estopTitle(has: (cap: Capability) => boolean): string {
  if (has("nanonis")) {
    return tr("紧急停止：中止任务 + 停止运动 + 退针", "Emergency stop: abort task + stop motion + retract tip");
  }
  return tr(
    "紧急停止：中止任务 + 停止运动 + 关激光与快门 + 磁体停止扫场 + 加热关闭",
    "Emergency stop: abort task + stop motion + lasers off and shutters closed + magnet ramp stopped + heaters off",
  );
}
