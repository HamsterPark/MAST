"""Analysis detectors: agent-written ``detect(frame)`` functions run on every new frame.

README
------
Design contract ``docs/v2/architecture/mast7_vista.md`` §7. An external agent registers a small
Python function; MAST runs it on each newly archived scan or spectrum and, on a hit, wakes the
agent through :class:`mast.vista.wait.WaitHub` (``hub.publish("detector", ...)``). A detector
only ever *looks*: it runs in :mod:`mast.pyexec` (a separate interpreter started from a scratch
environment: no instrument ports, existing measurement files protected, killable, memory-capped)
and never in the server process. Acting on a hit is the agent's decision, through ``act``.

The detector code defines ``def detect(frame)`` and returns a falsy value (no hit), ``True``, or
``{"hit": bool, "message": str, "value": ...}`` (a dict without ``hit`` counts as a hit). The
``frame`` it receives (see ``Frame`` in :data:`HARNESS`):

* ``frame.kind`` ``"scan"`` | ``"spectrum"``; ``frame.fid`` (``"t0007.s0"``);
* scans: ``frame.channels`` {channel: forward pass, 2-D float64, SI units, row 0 = top edge,
  NaN = not acquired}, ``frame.backward`` {channel: backward pass, un-mirrored};
* spectra: ``frame.columns`` {column: 1-D float64, SI}; the first column is the sweep;
* ``frame.units``, ``frame.meta`` (the archive record: geometry, bias, setpoint, scan
  direction, ...), and the conveniences ``frame.geometry``, ``frame.bias_v``,
  ``frame.setpoint_a``, ``frame.nm_per_px``.

Only saved scans (``s``) and spectra (``d``) are run; partial snapshots and derived images never.

Execution and limits
~~~~~~~~~~~~~~~~~~~~
* One worker thread per manager; runs are serial. :meth:`DetectorManager.on_frame` only enqueues
  (one run per matching enabled detector); the queue holds ``QUEUE_MAX`` runs and drops the
  oldest when full (counted in ``dropped``).
* Each run is one ``mast.pyexec.execute.run`` of a generated harness script (:data:`HARNESS`)
  inside the workspace's pyexec session (``mast.pyexec.session.get_session``, provisioned once
  per manager, again only if it was pruned); the harness loads the frame's
  archived ``.npz`` read-only, imports the detector code from a file, calls ``detect`` and writes
  ``result.json``. Wall clock ``max_runtime_s`` (default 20, 1..120) for the whole process, then
  the process tree is killed; memory capped at ``memory_bytes`` (default 2 GiB, Job Object).
* ``max_enabled`` (8) detectors may be enabled at once. A detector is auto-disabled, with
  ``disabled_reason``, after ``max_consecutive_errors`` (5) failed runs in a row or when it hits
  more than ``hits_per_hour`` (30) times within an hour.
* Hits wake the agent at most ``wakes_per_hour`` (60) times per hour across all detectors; a hit
  beyond that is recorded with ``suppressed: true`` and published nowhere (the same circuit
  breaker idea as ``core/wake_scheduler.py``). Auto-disable notices are always published.
* Detectors (code included), their counters and the last ``RECENT_HITS`` hits persist in
  ``store_path`` (``detectors.json``, atomic replace). The hourly windows live in memory.

Events: hits and auto-disables are published as ``hub.publish("detector", event)`` with
``event = {"kind": "hit" | "disabled", "detector_id", "name", "fid", "frame_kind", "message",
"value" | "reason", "t"}`` and are handed to ``on_event`` (if given; suppressed hits included,
with ``"suppressed": true``) so the host can log them.
"""
