HARNESS = r'''# Generated by mast.vista.detectors: run one analysis detector on one archived frame.
# RUN holds input.json and detector.py; the outcome is written to RUN/result.json.
import importlib.util
import json
import math
import os
import sys
import time
import traceback

RUN = os.path.abspath(__RUN_DIR__)
MESSAGE_CHARS = __MESSAGE_CHARS__


def _finish(payload):
    tmp = os.path.join(RUN, "result.json.tmp")
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, ensure_ascii=False, allow_nan=False)
    os.replace(tmp, os.path.join(RUN, "result.json"))


def _plain(o, depth=0):
    """A JSON-safe copy of a detector's value (numpy scalars and small arrays included)."""
    import numpy as np

    if depth > 8:
        return repr(o)[:200]
    if o is None or isinstance(o, (bool, str, int)):
        return o
    if isinstance(o, float):
        return o if math.isfinite(o) else None
    if isinstance(o, np.bool_):
        return bool(o)
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, np.floating):
        f = float(o)
        return f if math.isfinite(f) else None
    if isinstance(o, np.ndarray):
        if o.size > 10000:
            return {"_array_shape": list(o.shape), "note": "too large; return a summary instead"}
        return _plain(o.tolist(), depth + 1)
    if isinstance(o, dict):
        return {str(k): _plain(v, depth + 1) for k, v in o.items()}
    if isinstance(o, (list, tuple, set, frozenset)):
        return [_plain(v, depth + 1) for v in o]
    return repr(o)[:200]


def _outcome(out):
    import numpy as np

    usage = "return False/None (no hit), True, or {'hit': bool, 'message': str, 'value': ...}"
    if isinstance(out, np.ndarray):
        raise TypeError("detect() returned an array; " + usage)
    if isinstance(out, dict):
        hit = out.get("hit", True)
        if isinstance(hit, np.ndarray):
            raise TypeError("'hit' is an array; it must be a single bool")
        msg = out.get("message")
        return bool(hit), ("" if msg is None else str(msg))[:MESSAGE_CHARS], _plain(out.get("value"))
    if isinstance(out, (bool, np.bool_)):
        return bool(out), "", None
    if out is None:
        return False, "", None
    try:
        truthy = bool(out)
    except Exception:
        truthy = True
    if not truthy:
        return False, "", None
    raise TypeError("detect() returned a %s; %s" % (type(out).__name__, usage))


class Frame:
    """What detect(frame) receives.

    kind      "scan" or "spectrum";   fid   the frame id, e.g. "t0007.s0"
    channels  scans: {channel: forward pass, 2-D float64, SI units, row 0 = top edge, NaN = not acquired}
    backward  scans: {channel: backward pass, un-mirrored} for the channels that have one
    columns   spectra: {column: 1-D float64, SI units}; the first column is the sweep
    units     {channel or column: SI unit}
    meta      the archive record: geometry {cx_nm, cy_nm, w_nm, h_nm, angle_deg, nx, ny}, bias_v,
              setpoint_a, scan_dir, rec_time, nm_per_px, source_name, units, extra
    geometry, bias_v, setpoint_a, nm_per_px: shortcuts into meta
    """

    def __init__(self, spec, arrays):
        self.fid = spec["fid"]
        self.kind = spec["kind"]
        self.meta = spec["meta"]
        self.units = dict(spec.get("units") or {})
        self.channels, self.backward, self.columns = {}, {}, {}
        if self.kind == "scan":
            for key, a in arrays.items():
                name, _, direction = key.rpartition("/")
                (self.backward if direction == "backward" else self.channels)[name] = a
        else:
            self.columns = dict(arrays)
        self.geometry = dict(self.meta.get("geometry") or {})
        self.bias_v = self.meta.get("bias_v")
        self.setpoint_a = self.meta.get("setpoint_a")
        self.nm_per_px = self.meta.get("nm_per_px")

    def __repr__(self):
        names = sorted(self.channels) if self.kind == "scan" else list(self.columns)
        return "<Frame %s %s %s>" % (self.fid, self.kind, names)


def main():
    with open(os.path.join(RUN, "input.json"), encoding="utf-8") as fh:
        spec = json.load(fh)
    import numpy as np

    arrays = {}
    with np.load(spec["npz"], allow_pickle=False) as z:
        for i, key in enumerate(spec["array_keys"]):
            arrays[key] = np.array(z["a%d" % i], dtype=np.float64)
    frame = Frame(spec, arrays)
    mod_spec = importlib.util.spec_from_file_location("mast_detector", os.path.join(RUN, "detector.py"))
    module = importlib.util.module_from_spec(mod_spec)
    mod_spec.loader.exec_module(module)
    detect = getattr(module, "detect", None)
    if not callable(detect):
        raise TypeError("the detector code defines no detect(frame) function")
    t0 = time.perf_counter()
    out = detect(frame)
    took = time.perf_counter() - t0
    hit, message, value = _outcome(out)
    _finish({"ok": True, "hit": hit, "message": message, "value": value, "detect_s": round(took, 4)})


if __name__ == "__main__":
    try:
        main()
    except BaseException as exc:
        tb = traceback.format_exc()
        try:
            _finish({"ok": False, "error": ("%s: %s" % (type(exc).__name__, exc))[:1000],
                     "traceback": tb[-4000:]})
        except Exception:
            traceback.print_exc()
        sys.exit(1)
'''


class DetectorError(Exception):
    """A refused detector operation. ``status`` is the HTTP status the ext route answers with,
    ``code`` its ``error`` code; ``extra`` goes into the error body."""

    def __init__(self, status: int, code: str, detail: str, **extra: Any) -> None:
        super().__init__(detail)
        self.status = int(status)
        self.code = code
        self.detail = detail
        self.extra = extra


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ── validation (nothing here executes the code) ──────────────────────────────
def _defines_detect(tree: ast.Module) -> bool:
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "detect":
            return True
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "detect"
                                                for t in node.targets):
            return True
        if isinstance(node, ast.ImportFrom) and any((a.asname or a.name) == "detect"
                                                    for a in node.names):
            return True
    return False


def validate_code(code: Any) -> None:
    """Size, syntax (``compile`` only, never executed) and a top-level ``detect``.
    Raises ``ValueError`` with a message the agent can act on."""
    if not isinstance(code, str) or not code.strip():
        raise ValueError("code is empty; it must define def detect(frame)")
    size = len(code.encode("utf-8"))
    if size > MAX_CODE_BYTES:
        raise ValueError(f"code is {size} bytes; the limit is {MAX_CODE_BYTES}")
    try:
        tree = ast.parse(code, filename="detector.py")
        compile(tree, "detector.py", "exec")
    except SyntaxError as exc:
        raise ValueError(f"code does not compile: {exc.msg} (line {exc.lineno})") from None
    except ValueError as exc:
        raise ValueError(f"code does not compile: {exc}") from None
    if any(isinstance(n, ast.AsyncFunctionDef) and n.name == "detect" for n in tree.body):
        raise ValueError("detect must be a plain function (def detect(frame)), not async")
    if not _defines_detect(tree):
        raise ValueError("code must define a top-level function detect(frame)")


def _clean_name(name: Any) -> str:
    s = str(name or "").strip()
    if not s:
        raise ValueError("name is empty")
    if len(s) > MAX_NAME_CHARS:
        raise ValueError(f"name is longer than {MAX_NAME_CHARS} characters")
    return s


def _clean_applies_to(applies_to: Any) -> list[str]:
    items = [applies_to] if isinstance(applies_to, str) else list(applies_to or [])
    out: list[str] = []
    for k in items:
        if k not in APPLIES_TO:
            raise ValueError(f"applies_to {k!r} is not one of {list(APPLIES_TO)}")
        if k not in out:
            out.append(k)
    if not out:
        raise ValueError(f"applies_to must name at least one of {list(APPLIES_TO)}")
    return out


def _clean_runtime(v: Any) -> float:
    if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) \
            or not MIN_RUNTIME_S <= v <= MAX_RUNTIME_S:
        raise ValueError(f"max_runtime_s must be a number within {MIN_RUNTIME_S:g}..{MAX_RUNTIME_S:g}")
    return float(v)


def _new_stats() -> dict:
    return {"runs": 0, "hits": 0, "suppressed": 0, "errors": 0, "timeouts": 0,
            "consecutive_errors": 0, "dropped": 0, "last_run_at": None, "last_hit_at": None,
            "last_error": "", "last_elapsed_s": None, "total_elapsed_s": 0.0}


def _cap_value(v: Any) -> Any:
    try:
        s = json.dumps(v, ensure_ascii=False, allow_nan=False)
    except (TypeError, ValueError):
        return repr(v)[:300]
    if len(s) <= VALUE_JSON_CHARS:
        return v
    return {"_truncated": True, "chars": len(s), "preview": s[:300]}


def _tail(s: Any, n: int = OUTPUT_TAIL_CHARS) -> str:
    s = str(s or "")
    return s if len(s) <= n else "..." + s[-n:]


def _result(**kw: Any) -> dict:
    """A run result with every key present."""
    out = {"ok": False, "hit": False, "message": "", "value": None, "error": "", "timed_out": False,
           "elapsed_s": 0.0}
    out.update(kw)
    return out


@dataclass
class _Det:
    id: str
    name: str
    code: str
    applies_to: list[str]
    description: str = ""
    max_runtime_s: float = DEFAULT_RUNTIME_S
    created_by: str = ""
    created_at: str = ""
    enabled: bool = True
    disabled_reason: str = ""
    disabled_at: str | None = None
    stats: dict = field(default_factory=_new_stats)
    recent_hits: list[dict] = field(default_factory=list)
    hit_times: deque = field(default_factory=deque, repr=False)     # monotonic; not persisted

    def record(self) -> dict:
        return {"id": self.id, "name": self.name, "description": self.description,
                "applies_to": list(self.applies_to), "max_runtime_s": self.max_runtime_s,
                "created_by": self.created_by, "created_at": self.created_at,
                "enabled": self.enabled, "disabled_reason": self.disabled_reason,
                "disabled_at": self.disabled_at, "code": self.code, "stats": dict(self.stats),
                "recent_hits": [dict(h) for h in self.recent_hits]}

    @classmethod
    def from_record(cls, rec: dict) -> "_Det":
        code = str(rec["code"])
        validate_code(code)
        det = cls(id=str(rec["id"]), name=_clean_name(rec["name"]), code=code,
                  applies_to=_clean_applies_to(rec.get("applies_to")),
                  description=str(rec.get("description") or "")[:MAX_DESCRIPTION_CHARS],
                  max_runtime_s=_clean_runtime(rec.get("max_runtime_s", DEFAULT_RUNTIME_S)),
                  created_by=str(rec.get("created_by") or ""), created_at=str(rec.get("created_at") or ""),
                  enabled=bool(rec.get("enabled", True)),
                  disabled_reason=str(rec.get("disabled_reason") or ""),
                  disabled_at=rec.get("disabled_at"))
        det.stats.update({k: v for k, v in dict(rec.get("stats") or {}).items() if k in det.stats})
        det.recent_hits = [dict(h) for h in (rec.get("recent_hits") or []) if isinstance(h, dict)][-RECENT_HITS:]
        return det


class DetectorManager:
    """The analysis detectors of one workspace (see the module docstring). Thread-safe."""

    def __init__(self, store_path: Path | str, *, hub: Any = None,
                 run_frame: Callable[..., dict] | None = None, max_enabled: int = MAX_ENABLED,
                 wakes_per_hour: int = WAKES_PER_HOUR, hits_per_hour: int = HITS_PER_HOUR,
                 max_consecutive_errors: int = MAX_CONSECUTIVE_ERRORS, queue_max: int = QUEUE_MAX,
                 workspace_id: str | None = None, session_factory: Callable[[], Any] | None = None,
                 memory_bytes: int = MEMORY_BYTES, on_event: Callable[[dict], None] | None = None,
                 clock: Callable[[], float] = time.monotonic) -> None:
        """``run_frame(detector, archive, entry, *, timeout_s) -> result`` replaces the pyexec run
        (tests, or a host with its own executor); ``detector`` is ``{id, name, code, applies_to,
        max_runtime_s}`` and the result has the keys of a :meth:`test` answer. ``session_factory``
        returns the pyexec session runs use (default: one per workspace via ``get_session``)."""
        self.store_path = Path(store_path)
        self._hub = hub
        self._run_frame = run_frame or self._run_in_pyexec
        self._max_enabled = int(max_enabled)
        self._wakes_per_hour = int(wakes_per_hour)
        self._hits_per_hour = int(hits_per_hour)
        self._max_errors = int(max_consecutive_errors)
        self._queue_max = max(1, int(queue_max))
        self._workspace_id = str(workspace_id or self.store_path.parent.name or "workspace")
        self._session_factory = session_factory or self._default_session
        self._memory_bytes = int(memory_bytes)
        self._on_event = on_event
        self._clock = clock
        self._lock = threading.RLock()            # detectors, stats, the wake window
        self._io_lock = threading.Lock()          # one store writer at a time, newest state last
        self._qcv = threading.Condition()         # the run queue and the worker
        self._session_lock = threading.Lock()
        self._pysession: Any = None
        self._dets: dict[str, _Det] = {}
        self._wakes: deque = deque()
        self._queue: deque = deque()
        self._dropped = 0
        self._running: str | None = None
        self._worker: threading.Thread | None = None
        self._closed = False
        self.load_warnings: list[str] = []
        self._load()

    # ── store ───────────────────────────────────────────────────────────────
    def _load(self) -> None:
        p = self.store_path
        if not p.is_file():
            return
        try:
            doc = json.loads(p.read_text(encoding="utf-8"))
            rows = doc.get("detectors") if isinstance(doc, dict) else None
            if not isinstance(rows, list):
                raise ValueError("no 'detectors' list")
        except (OSError, ValueError) as exc:
            bad = p.with_name(f"{p.name}.corrupt-{int(time.time())}")
            try:
                os.replace(p, bad)
                where = f"moved to {bad.name}"
            except OSError:
                where = "left in place"
            self.load_warnings.append(f"{p.name} unreadable ({exc}); {where}; starting empty")
            logger.warning("detectors: %s", self.load_warnings[-1])
            return
        for n, rec in enumerate(rows):
            try:
                det = _Det.from_record(rec)
            except (KeyError, TypeError, ValueError) as exc:
                self.load_warnings.append(f"detector record {n} skipped: {exc}")
                continue
            self._dets[det.id] = det
        for w in self.load_warnings:
            logger.warning("detectors: %s", w)

    def _save(self) -> bool:
        """Write the store (atomic replace). ``False`` (and a warning) when the disk refused."""
        with self._io_lock:
            with self._lock:
                doc = {"schema": STORE_SCHEMA, "saved_at": _now_iso(),
                       "detectors": [d.record() for d in self._dets.values()]}
            p = self.store_path
            tmp = p.with_name(p.name + ".tmp")
            try:
                p.parent.mkdir(parents=True, exist_ok=True)
                with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(json.dumps(doc, ensure_ascii=False, indent=1, default=str))
                    fh.flush()
                    os.fsync(fh.fileno())
                os.replace(tmp, p)
                return True
            except OSError as exc:
                logger.warning("detectors: store write failed (%s); state kept in memory", exc)
                return False

    # ── views ───────────────────────────────────────────────────────────────
    def _view(self, d: _Det, *, code: bool = False, hits: bool = False) -> dict:
        now = self._clock()
        v = {"id": d.id, "name": d.name, "description": d.description,
             "applies_to": list(d.applies_to), "max_runtime_s": d.max_runtime_s,
             "enabled": d.enabled, "disabled_reason": d.disabled_reason or None,
             "disabled_at": d.disabled_at, "created_by": d.created_by, "created_at": d.created_at,
             "code_bytes": len(d.code.encode("utf-8")),
             "code_sha256": hashlib.sha256(d.code.encode("utf-8")).hexdigest()[:16],
             "hits_last_hour": sum(1 for t in d.hit_times if now - t <= HOUR_S),
             "stats": dict(d.stats)}
        if code:
            v["code"] = d.code
        if hits:
            v["recent_hits"] = [dict(h) for h in d.recent_hits]
        return v

    def list(self) -> list[dict]:
        """Every detector (no code, no hits), oldest first."""
        with self._lock:
            return [self._view(d) for d in self._dets.values()]

    def get(self, det_id: str) -> dict | None:
        """One detector with its code and recent hits, or ``None``."""
        with self._lock:
            d = self._dets.get(str(det_id))
            return None if d is None else self._view(d, code=True, hits=True)

    def status(self) -> dict:
        """Queue and limits (for status pages and the list endpoint)."""
        now = self._clock()
        with self._lock:
            enabled = sum(1 for d in self._dets.values() if d.enabled)
            wakes = sum(1 for t in self._wakes if now - t <= HOUR_S)
        with self._qcv:
            queued, dropped, running = len(self._queue), self._dropped, self._running
            alive = self._worker is not None and self._worker.is_alive()
        return {"enabled": enabled, "max_enabled": self._max_enabled, "queued": queued,
                "queue_max": self._queue_max, "dropped": dropped, "running": running,
                "worker_alive": alive, "wakes_last_hour": wakes,
                "wakes_per_hour": self._wakes_per_hour, "hits_per_hour": self._hits_per_hour,
                "max_consecutive_errors": self._max_errors}

    def _need(self, det_id: str) -> _Det:
        d = self._dets.get(str(det_id))
        if d is None:
            raise DetectorError(404, "unknown_detector", f"no detector {det_id!r} in this workspace",
                                available=list(self._dets)[:20])
        return d

    # ── management ──────────────────────────────────────────────────────────
    def create(self, *, name: str, code: str, applies_to: Any, description: str = "",
               max_runtime_s: float = DEFAULT_RUNTIME_S, created_by: str = "") -> dict:
        """Register an enabled detector. The same name with the same code and kinds returns the
        existing detector (``existing: true``), so a retried request does not create two.
        ``ValueError`` for invalid input; :class:`DetectorError` for a conflict or a limit."""
        name = _clean_name(name)
        validate_code(code)
        kinds = _clean_applies_to(applies_to)
        description = str(description or "").strip()
        if len(description) > MAX_DESCRIPTION_CHARS:
            raise ValueError(f"description is longer than {MAX_DESCRIPTION_CHARS} characters")
        runtime_s = _clean_runtime(max_runtime_s)
        with self._lock:
            same = next((d for d in self._dets.values() if d.name == name), None)
            if same is not None:
                if same.code == code and same.applies_to == kinds:
                    return {**self._view(same), "existing": True}
                raise DetectorError(409, "detector_name_taken",
                                    f"a detector named {name!r} already exists ({same.id}); "
                                    "delete it first or choose another name", detector_id=same.id)
            if len(self._dets) >= MAX_DETECTORS:
                raise DetectorError(409, "too_many_detectors",
                                    f"this workspace already has {len(self._dets)} detectors; "
                                    "delete unused ones first")
            enabled = [d.id for d in self._dets.values() if d.enabled]
            if len(enabled) >= self._max_enabled:
                raise DetectorError(409, "too_many_enabled",
                                    f"{len(enabled)} detectors are enabled (limit {self._max_enabled}); "
                                    "disable one first", enabled=enabled)
            det_id = f"det-{secrets.token_hex(4)}"
            while det_id in self._dets:
                det_id = f"det-{secrets.token_hex(4)}"
            det = _Det(id=det_id, name=name, code=code, applies_to=kinds, description=description,
                       max_runtime_s=runtime_s, created_by=str(created_by or "")[:120],
                       created_at=_now_iso())
            self._dets[det.id] = det
            view = self._view(det)
        if not self._save():
            view["persist_failed"] = True
        return view

    def set_enabled(self, det_id: str, enabled: bool) -> dict:
        """Enable (clears an auto-disable: reason, error streak and hourly hit window) or
        disable. :class:`DetectorError` for an unknown id or the enabled limit."""
        with self._lock:
            d = self._need(det_id)
            if enabled and not d.enabled:
                others = [x.id for x in self._dets.values() if x.enabled]
                if len(others) >= self._max_enabled:
                    raise DetectorError(409, "too_many_enabled",
                                        f"{len(others)} detectors are enabled (limit "
                                        f"{self._max_enabled}); disable one first", enabled=others)
                d.enabled, d.disabled_reason, d.disabled_at = True, "", None
                d.stats["consecutive_errors"] = 0
                d.hit_times.clear()
            elif not enabled and d.enabled:
                d.enabled, d.disabled_reason, d.disabled_at = False, "disabled on request", _now_iso()
            view = self._view(d)
        if not enabled:
            self._unqueue(d.id)
        if not self._save():
            view["persist_failed"] = True
        return view

    def delete(self, det_id: str) -> bool:
        with self._lock:
            d = self._dets.pop(str(det_id), None)
        if d is None:
            return False
        self._unqueue(d.id)
        self._save()
        return True

    def _unqueue(self, det_id: str) -> None:
        with self._qcv:
            self._queue = deque(item for item in self._queue if item[0] != det_id)

    # ── runs ────────────────────────────────────────────────────────────────
    def test(self, det_id: str, archive: Any, fid: str) -> dict:
        """Run one detector on one archived frame now (synchronously, also when disabled).
        Nothing is recorded or published; the answer carries the detector's output tails."""
        with self._lock:
            d = self._need(det_id)
            snap = self._snapshot(d)
        try:
            entry = archive.get(fid)
        except KeyError as exc:
            raise DetectorError(404, "unknown_frame", str(exc.args[0] if exc.args else exc)) from None
        kind = KIND_OF_ENTRY.get(entry.kind)
        if kind is None:
            raise DetectorError(422, "frame_not_applicable",
                                f"{entry.fid} is a {entry.kind_name} frame; detectors run on saved "
                                "scans and spectra only")
        if kind not in snap["applies_to"]:
            raise DetectorError(422, "frame_not_applicable",
                                f"{snap['id']} applies to {snap['applies_to']}; {entry.fid} is a {kind}")
        res = self._execute(snap, archive, entry)
        return {"detector_id": snap["id"], "name": snap["name"], "frame": entry.fid,
                "frame_kind": kind, **res, "recorded": False}

    def on_frame(self, archive: Any, entry: Any) -> None:
        """A frame was archived: queue one run per enabled detector that applies. Never blocks
        on a run; returns at once."""
        kind = KIND_OF_ENTRY.get(getattr(entry, "kind", None))
        if kind is None:
            return
        with self._lock:
            ids = [d.id for d in self._dets.values() if d.enabled and kind in d.applies_to]
        if not ids:
            return
        dropped: list[str] = []
        with self._qcv:
            if self._closed:
                return
            for det_id in ids:
                if len(self._queue) >= self._queue_max:
                    dropped.append(self._queue.popleft()[0])
                    self._dropped += 1
                self._queue.append((det_id, archive, entry))
            self._qcv.notify()
        if dropped:
            logger.warning("detectors: run queue full (%d); dropped the oldest %d run(s)",
                           self._queue_max, len(dropped))
            with self._lock:
                for det_id in dropped:
                    if det_id in self._dets:
                        self._dets[det_id].stats["dropped"] += 1
        self._ensure_worker()

    def _ensure_worker(self) -> None:
        with self._qcv:
            if self._closed or (self._worker is not None and self._worker.is_alive()):
                return
            self._worker = threading.Thread(target=self._loop, daemon=True,
                                            name=f"vista-detectors-{self._workspace_id}")
            self._worker.start()

    def _loop(self) -> None:
        while True:
            with self._qcv:
                while not self._queue and not self._closed:
                    self._qcv.wait(timeout=1.0)
                if self._closed:
                    return
                det_id, archive, entry = self._queue.popleft()
                self._running = det_id
            try:
                self._process(det_id, archive, entry)
            except Exception:  # noqa: BLE001 - the worker outlives any single run
                logger.exception("detectors: run of %s on %s failed", det_id,
                                 getattr(entry, "fid", "?"))
            finally:
                with self._qcv:
                    self._running = None

    def _process(self, det_id: str, archive: Any, entry: Any) -> None:
        with self._lock:
            d = self._dets.get(det_id)
            if d is None or not d.enabled:
                return
            snap = self._snapshot(d)
        self._record(det_id, entry, self._execute(snap, archive, entry))

    @staticmethod
    def _snapshot(d: _Det) -> dict:
        return {"id": d.id, "name": d.name, "code": d.code, "applies_to": list(d.applies_to),
                "max_runtime_s": d.max_runtime_s}

    def _execute(self, snap: dict, archive: Any, entry: Any) -> dict:
        t0 = time.monotonic()
        try:
            res = self._run_frame(snap, archive, entry, timeout_s=snap["max_runtime_s"])
        except Exception as exc:  # noqa: BLE001 - an executor failure is the run's error
            logger.warning("detectors: executor failed for %s on %s: %s", snap["id"],
                           getattr(entry, "fid", "?"), exc)
            res = {"ok": False, "error": f"executor failed: {type(exc).__name__}: {exc}"}
        res = _result(**({"elapsed_s": round(time.monotonic() - t0, 3)} | dict(res or {})))
        res["message"] = str(res.get("message") or "")[:MESSAGE_CHARS]
        res["value"] = _cap_value(res.get("value"))
        if not res["ok"]:
            res["hit"] = False
            res["error"] = str(res.get("error") or "the run failed without a reason")
        return res

    def _take_wake(self, now: float) -> bool:
        while self._wakes and now - self._wakes[0] > HOUR_S:
            self._wakes.popleft()
        if len(self._wakes) >= self._wakes_per_hour:
            return False
        self._wakes.append(now)
        return True

    def _disable(self, d: _Det, reason: str) -> None:
        d.enabled, d.disabled_reason, d.disabled_at = False, reason, _now_iso()

    def _record(self, det_id: str, entry: Any, res: dict) -> None:
        """Count one finished run; on a hit decide wake vs suppressed; auto-disable; persist;
        then publish (outside the lock)."""
        fid = str(getattr(entry, "fid", "") or "")
        kind = KIND_OF_ENTRY.get(getattr(entry, "kind", None), "")
        now = self._clock()
        out: list[tuple[dict, bool]] = []          # (event, publish to the hub)
        with self._lock:
            d = self._dets.get(det_id)
            if d is None:
                return                             # deleted while it ran
            base = {"detector_id": d.id, "name": d.name, "fid": fid, "frame_kind": kind}
            st = d.stats
            st["runs"] += 1
            st["last_run_at"] = _now_iso()
            st["last_elapsed_s"] = res.get("elapsed_s")
            st["total_elapsed_s"] = round(float(st.get("total_elapsed_s") or 0.0)
                                          + float(res.get("elapsed_s") or 0.0), 3)
            reason = ""
            if not res["ok"]:
                st["errors"] += 1
                st["consecutive_errors"] += 1
                st["timeouts"] += 1 if res.get("timed_out") else 0
                st["last_error"] = f"{fid}: {res['error']}"[:MESSAGE_CHARS]
                if d.enabled and st["consecutive_errors"] >= self._max_errors:
                    reason = (f"auto-disabled after {st['consecutive_errors']} consecutive errors "
                              f"(last on {fid}: {str(res['error'])[:200]})")
            else:
                st["consecutive_errors"] = 0
                if res["hit"]:
                    st["hits"] += 1
                    st["last_hit_at"] = _now_iso()
                    d.hit_times.append(now)
                    while d.hit_times and now - d.hit_times[0] > HOUR_S:
                        d.hit_times.popleft()
                    wake = self._take_wake(now)
                    if not wake:
                        st["suppressed"] += 1
                    d.recent_hits.append({"fid": fid, "t": _now_iso(), "message": res["message"],
                                          "value": res["value"], "suppressed": not wake,
                                          "elapsed_s": res.get("elapsed_s")})
                    del d.recent_hits[:-RECENT_HITS]
                    ev = {"kind": "hit", **base, "message": res["message"], "value": res["value"],
                          "t": time.time()}
                    out.append((ev if wake else {**ev, "suppressed": True}, wake))
                    if d.enabled and len(d.hit_times) > self._hits_per_hour:
                        reason = (f"auto-disabled: {len(d.hit_times)} hits within an hour "
                                  f"(limit {self._hits_per_hour}); make it more selective")
            if reason:
                self._disable(d, reason)
                out.append(({"kind": "disabled", **base, "reason": reason, "t": time.time()}, True))
        self._save()
        with self._qcv:
            closed = self._closed
        if closed:
            return
        for ev, publish in out:
            if publish and self._hub is not None:
                try:
                    self._hub.publish("detector", ev)
                except Exception:  # noqa: BLE001 - recording the hit already happened
                    logger.warning("detectors: hub publish failed", exc_info=True)
            if self._on_event is not None:
                try:
                    self._on_event(dict(ev))
                except Exception:  # noqa: BLE001
                    logger.warning("detectors: on_event callback failed", exc_info=True)

    def close(self, timeout_s: float = CLOSE_JOIN_S) -> None:
        """Stop the worker: queued runs are dropped; a run in progress finishes on its own
        (bounded by its ``max_runtime_s``) and is recorded but not published. Bounded join."""
        with self._qcv:
            self._closed = True
            self._queue.clear()
            self._qcv.notify_all()
            t = self._worker
        if t is not None and t.is_alive() and t is not threading.current_thread():
            t.join(max(0.0, float(timeout_s)))
            if t.is_alive():
                logger.warning("detectors: the worker is still finishing a run; not waiting longer "
                               "(the run ends within its max_runtime_s)")

    # ── pyexec ──────────────────────────────────────────────────────────────
    def _default_session(self) -> Any:
        from mast.pyexec.session import get_session

        return get_session(experiment_id=self._workspace_id,
                           thread_id=f"vista-detectors/{self._workspace_id}")

    def _session(self) -> Any:
        """The pyexec session runs use, provisioned once (``get_session`` re-copies the audit
        hook's ``sitecustomize.py`` on every call, which must not happen while a child of a
        concurrent run is starting); provisioned again only when its files are gone (pruned)."""
        with self._session_lock:
            s = self._pysession
            if s is None or not (Path(s.root) / "sitecustomize.py").is_file():
                s = self._pysession = self._session_factory()
            return s

    def _run_in_pyexec(self, det: dict, archive: Any, entry: Any, *, timeout_s: float) -> dict:
        """One harness run in a fresh pyexec interpreter (see :data:`HARNESS`)."""
        from mast.pyexec.execute import run
        from mast.pyexec.runtime import probe_runtime

        report = probe_runtime()
        rt = report.runtime
        if rt is None:
            return {"ok": False, "error": "no analysis Python runtime: " + report.why_not()}
        keys = list((getattr(entry, "extra", None) or {}).get("array_keys") or [])
        if not keys:
            return {"ok": False, "error": f"{entry.fid} has no archived values"}
        session = self._session()
        run_id = f"{det['id']}-{secrets.token_hex(4)}"
        run_rel = f"vista_detectors/{run_id}"
        stem = f"vista_det_{run_id}"
        run_dir = Path(session.root) / run_rel
        script = Path(session.root) / "code" / f"{stem}.py"
        try:
            run_dir.mkdir(parents=True)
            spec = {"fid": entry.fid, "kind": KIND_OF_ENTRY[entry.kind],
                    "npz": str(Path(archive.root) / f"{entry.fid}.npz"), "array_keys": keys,
                    "meta": entry.to_record(), "units": dict(entry.units or {})}
            (run_dir / "input.json").write_text(json.dumps(spec, ensure_ascii=False), encoding="utf-8")
            (run_dir / "detector.py").write_text(det["code"], encoding="utf-8")
            script.parent.mkdir(parents=True, exist_ok=True)
            script.write_text(HARNESS.replace("__RUN_DIR__", repr(run_rel))
                              .replace("__MESSAGE_CHARS__", str(MESSAGE_CHARS)), encoding="utf-8")
            res = run(session, f"code/{stem}.py", runtime=rt, timeout_s=float(timeout_s),
                      memory_bytes=self._memory_bytes)
            out = self._read_result(run_dir / "result.json")
        finally:
            shutil.rmtree(run_dir, ignore_errors=True)
            for p in (script, Path(session.logs_dir) / f"{stem}.out", Path(session.logs_dir) / f"{stem}.err"):
                try:
                    p.unlink()
                except OSError:
                    pass
        base = {"elapsed_s": round(float(res.duration_s), 3), "timed_out": bool(res.timed_out),
                "stdout": _tail(res.stdout), "stderr": _tail(res.stderr),
                "runtime_isolated": bool(rt.isolated)}
        if res.timed_out:
            return {**base, "ok": False,
                    "error": f"exceeded max_runtime_s={float(timeout_s):g}; the process was killed"}
        if out is None:
            why = res.killed_reason or f"the detector process exited with code {res.returncode} " \
                                       "without writing a result"
            return {**base, "ok": False, "error": why}
        if not out.get("ok"):
            return {**base, "ok": False, "error": str(out.get("error") or "detect() failed"),
                    "traceback": str(out.get("traceback") or "")}
        return {**base, "ok": True, "hit": bool(out.get("hit")), "message": out.get("message") or "",
                "value": out.get("value"), "detect_s": out.get("detect_s")}

    @staticmethod
    def _read_result(path: Path) -> dict | None:
        try:
            raw = path.read_text(encoding="utf-8")
        except OSError:
            return None
        try:
            out = json.loads(raw)
        except ValueError:
            return {"ok": False, "error": "the detector process wrote an unreadable result"}
        return out if isinstance(out, dict) else None


